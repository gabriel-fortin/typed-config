using NUnit.Framework;
using org.g14.FeatureFlags.Generation.CodeProduction;
using org.g14.FeatureFlags.Generation.CodeProduction.Models;
using static org.g14.FeatureFlags.Generation.Tests.TestHelpers;

namespace org.g14.FeatureFlags.Generation.Tests;

/** Tests the efficient source code creator:
    - Empty classes
    - Classes with single/multiple properties
    - Array properties (int[])
    - 2D array properties (int[][])
    - Using statements for required namespaces
    - Multiple namespace handling
    - Duplicate namespace deduplication
    - Error indicating classes with simple messages
    - Error classes with special character encoding
    - Unknown type class generation
    - Service collection extension method generation
 */

[TestFixture]
public class SimpleSourceCodeCreatorTests
{
    private SimpleSourceCodeCreator _creator = null!;
    private const string TestNamespace = "TestNamespace";

    [SetUp]
    public void SetUp()
    {
        _creator = new SimpleSourceCodeCreator(TestNamespace);
    }

    [Test]
    public void GetAppsettingsObjectClass_WithEmptyProperties_GeneratesEmptyClass()
    {
        // Arrange
        PropDetails[] props = Array.Empty<PropDetails>();
        string className = "EmptyClass";

        // Act
        SourceCodeDetails result = _creator.GetAppsettingsObjectClass(TestNamespace, props, className);

        // Assert
        string expected = $$"""
            {{Const.AutogeneratedHeader}}

            namespace TestNamespace;

            public class EmptyClass
            {
                
            }
            """;
        Assert.That(result.FileName, Is.EqualTo("EmptyClass.generated.cs"));
        Assert.That(NormalizeLineEndings(result.SourceCodeText), Is.EqualTo(NormalizeLineEndings(expected)));
    }

    [Test]
    public void GetAppsettingsObjectClass_WithSingleProperty_GeneratesClassWithOneProperty()
    {
        // Arrange
        PropDetails[] props = new[]
        {
            new PropDetails("string", null, "Name")
        };
        string className = "SimpleClass";

        // Act
        SourceCodeDetails result = _creator.GetAppsettingsObjectClass(TestNamespace, props, className);

        // Assert
        string expected = $$"""
            {{Const.AutogeneratedHeader}}
            
            namespace TestNamespace;

            public class SimpleClass
            {
                public required string Name { get; init; }
            }
            """;
        Assert.That(result.FileName, Is.EqualTo("SimpleClass.generated.cs"));
        Assert.That(NormalizeLineEndings(result.SourceCodeText), Is.EqualTo(NormalizeLineEndings(expected)));
    }

