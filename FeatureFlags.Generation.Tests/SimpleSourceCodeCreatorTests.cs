    [Test]
    public void GetServiceCollectionExtensionMethod_GeneratesExtensionMethodWithCorrectClassName()
    {
        // Arrange
        string className = "FlagsRootType";

        // Act
        SourceCodeDetails result = _creator.GetServiceCollectionExtensionMethod(className);

        // Assert
        string expected = $$"""
            {{Const.AutogeneratedHeader}}

            namespace TestNamespace;

            public static class ServiceCollectionExtensions
            {
                public static IServiceCollection AddGeneratedFeatureFlags(this IServiceCollection services)
                {
                    return services.AddSingleton<FlagsRootType>(services =>
                    {
                        string key = "FeatureFlags";
                        IConfiguration configuration = services.GetRequiredService<IConfiguration>();
                        IConfigurationSection configSection = configuration.GetSection(key);
                        return configSection.Get<FlagsRootType>();
                    });
                }
            }
            """;
        Assert.That(result.FileName, Is.EqualTo("ServiceCollectionExtensions.generated.cs"));
        Assert.That(NormalizeLineEndings(result.SourceCodeText), Is.EqualTo(NormalizeLineEndings(expected)));
    }
